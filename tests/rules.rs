fn is_link(repo: &Repo, rel: &str) -> bool {
    fs::symlink_metadata(repo.root.join(rel))
        .unwrap()
        .is_symlink()
}

fn init_with(repo: &Repo) -> std::process::Output {
    repo.install_self(VERSION);
    repo.atelier(&["init", "--version", VERSION])
}

