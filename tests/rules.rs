#[test]
fn a_symlinked_claude_md_stays_a_link_and_the_text_is_loaded_once() {
    // CLAUDE.md -> AGENTS.md
    let repo = Repo::new();
    repo.write("AGENTS.md", "# Mine\n");
    std::os::unix::fs::symlink("AGENTS.md", repo.root.join("CLAUDE.md")).unwrap();
    let out = init_with(&repo);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    assert!(is_link(&repo, "CLAUDE.md"));
    let agents = read(&repo, "AGENTS.md");
    assert!(agents.starts_with("# Mine\n\n<!-- atelier:begin"));
    assert!(!agents.contains("@AGENTS.md"), "{agents}");
    assert_eq!(read(&repo, "CLAUDE.md"), agents);
    assert_current(&repo, "CLAUDE.md -> AGENTS.md");
    let out = repo.atelier(&["rules"]);
    assert!(stdout(&out).contains("current"), "{}", stdout(&out));

    // CLAUDE.md -> AGENTS.md, both missing: the link is not replaced either.
    let repo = Repo::new();
    std::os::unix::fs::symlink("AGENTS.md", repo.root.join("CLAUDE.md")).unwrap();
    assert_eq!(code(&init_with(&repo)), 0);
    assert!(is_link(&repo, "CLAUDE.md"));
    assert!(read(&repo, "AGENTS.md").starts_with("<!-- atelier:begin"));
    assert_current(&repo, "dangling CLAUDE.md");

    // AGENTS.md -> docs/agents.md: the block is written to the target.
    let repo = Repo::new();
    repo.write("docs/agents.md", "# Docs\n");
    std::os::unix::fs::symlink("docs/agents.md", repo.root.join("AGENTS.md")).unwrap();
    assert_eq!(code(&init_with(&repo)), 0);
    assert!(is_link(&repo, "AGENTS.md"));
    assert!(read(&repo, "docs/agents.md").starts_with("# Docs\n\n<!-- atelier:begin"));
    assert_eq!(read(&repo, "CLAUDE.md"), "@AGENTS.md\n");
    assert_current(&repo, "AGENTS.md -> docs/agents.md");

    // AGENTS.md -> CLAUDE.md: the import is satisfied by the file itself.
    let repo = Repo::new();
    repo.write("CLAUDE.md", "notes\n");
    std::os::unix::fs::symlink("CLAUDE.md", repo.root.join("AGENTS.md")).unwrap();
    assert_eq!(code(&init_with(&repo)), 0);
    assert!(is_link(&repo, "AGENTS.md"));
    let claude = read(&repo, "CLAUDE.md");
    assert!(claude.starts_with("notes\n\n<!-- atelier:begin"));
    assert!(!claude.contains("@AGENTS.md"));
    assert_current(&repo, "AGENTS.md -> CLAUDE.md");

    // An import file linked to some other file gets its line there.
    let repo = Repo::new();
    repo.write("docs/claude.md", "mine\n");
    std::os::unix::fs::symlink("docs/claude.md", repo.root.join("CLAUDE.md")).unwrap();
    assert_eq!(code(&init_with(&repo)), 0);
    assert!(is_link(&repo, "CLAUDE.md"));
    assert_eq!(read(&repo, "docs/claude.md"), "mine\n@AGENTS.md\n");
    assert_current(&repo, "CLAUDE.md -> docs/claude.md");
}

