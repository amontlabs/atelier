#[test]
fn markers_in_code_comments_or_longer_lines_are_not_the_block() {
    // A fenced example of the whole block is user text, not the block.
    let repo = Repo::new();
    let example = format!("# Docs\n\n```markdown\n{BEGIN}\nold\n{END}\n```\n");
    repo.write("AGENTS.md", &example);
    assert_eq!(code(&init_with(&repo)), 0);
    let text = read(&repo, "AGENTS.md");
    assert!(text.starts_with(&format!("{example}\n{BEGIN}")), "{text}");
    assert_eq!(text.matches(BEGIN).count(), 2);
    assert_current(&repo, "fenced example");

    // One quoted marker in a fence or comment, and lines that only start like a marker.
    for body in [
        format!("```\n{BEGIN}\n```\n"),
        format!("<!--\n{END}\n-->\n"),
        "<!-- atelier:beginner notes -->\n".to_owned(),
        "<!-- atelier:begin x -->\n".to_owned(),
    ] {
        let repo = Repo::new();
        repo.write("AGENTS.md", &body);
        let out = init_with(&repo);
        assert_eq!(code(&out), 0, "{body}: {}", stderr(&out));
        assert!(read(&repo, "AGENTS.md").starts_with(&body), "{body}");
        assert_current(&repo, &body);
        assert_eq!(code(&repo.atelier(&["rules"])), 0);
    }
}

#[test]
fn a_marker_line_in_project_text_is_refused_before_anything_is_written() {
    let repo = inited();
    let before = read(&repo, "AGENTS.md");
    for (file, text, line) in [
        ("binding.md", format!("fine\n{END}\n"), 2),
        ("worker.md", format!("a\nb\n{BEGIN}\n"), 3),
        ("extra.md", format!("{BEGIN}\r\n"), 1),
    ] {
        repo.write(&format!(".atelier/project/{file}"), &text);
        let out = repo.atelier(&["rules"]);
        assert_eq!(code(&out), 4, "{file}");
        let err = stderr(&out);
        assert!(
            err.contains(&format!(".atelier/project/{file}:{line}")),
            "{err}"
        );
        assert_eq!(read(&repo, "AGENTS.md"), before);
        fs::remove_file(repo.root.join(format!(".atelier/project/{file}"))).unwrap();
        assert_eq!(code(&repo.atelier(&["rules"])), 0);
    }
    // A fenced marker line in project text is refused as well; a longer line is plain text.
    repo.write(".atelier/project/binding.md", &format!("```\n{END}\n```\n"));
    assert_eq!(code(&repo.atelier(&["rules"])), 4);
    repo.write(
        ".atelier/project/binding.md",
        "<!-- atelier:end --> not a marker\n",
    );
    assert_eq!(code(&repo.atelier(&["rules"])), 0);
    assert_eq!(code(&repo.atelier(&["rules"])), 0);
}

