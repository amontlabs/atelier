#[test]
fn agents_prints_the_roles() {
    let repo = inited();
    let out = repo.atelier(&["agents"]);
    assert_eq!(code(&out), 4);
    assert!(stderr(&out).contains("agents.toml"));
    repo.write_agents_file(AGENTS);
    let out = repo.atelier(&["agents"]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    let text = stdout(&out);
    let lines: Vec<&str> = text.lines().collect();
    assert!(
        lines[0].starts_with("role") && lines[0].contains("for") && lines[0].ends_with("start")
    );
    assert!(lines[1].starts_with("build ") && lines[1].contains("an ordinary item or fix"));
    assert!(lines[1].ends_with("delegate_task, target.model = build"));
    assert!(lines[2].starts_with("build-hard"));
    assert_eq!(lines.len(), 7, "{text}");
    // A role the rules name must exist.
    repo.write_agents_file("[roles.build]\nfor = \"x\"\nstart = \"s\"\ntemplate = \"build\"\n");
    let out = repo.atelier(&["agents"]);
    assert_eq!(code(&out), 4);
    assert!(stderr(&out).contains("build-hard"));
}

/// A started branch: a worktree, a record, one commit on it.
fn start_branch(repo: &Repo, name: &str, lower: &str) -> std::path::PathBuf {
    if !git(&repo.root, &["status", "--porcelain"]).is_empty() {
        repo.commit_all("rules");
    }
    let wt = std::fs::canonicalize(repo.tmp.path())
        .unwrap()
        .join(format!("wt-{}", name.replace('/', "_")));
    git(
        &repo.root,
        &[
            "worktree",
            "add",
            "-q",
            "-b",
            name,
            wt.to_str().unwrap(),
            lower,
        ],
    );
    let base = git(&repo.root, &["rev-parse", lower]);
    let state = State::open(&repo.checkout()).unwrap();
    BranchRecord {
        name: name.to_owned(),
        lifetime: new_lifetime_id().unwrap(),
        lower: lower.to_owned(),
        lower_lifetime: None,
        base,
        state: BranchState::Active,
        pending: None,
    }
    .write(&state)
    .unwrap();
    wt
}

fn task_file(out: &std::process::Output) -> (String, String) {
    let line = stdout(out);
    let line = line.trim();
    let path = line
        .strip_prefix("Read ")
        .and_then(|l| l.strip_suffix(": it is your task."))
        .unwrap_or_else(|| panic!("{line}"));
    assert!(path.contains(".git/atelier/tasks/") && path.starts_with('/'));
    (path.to_owned(), fs::read_to_string(path).unwrap())
}

#[test]
fn task_renders_each_template() {
    let repo = inited();
    repo.write_agents_file(AGENTS);
    let wt = start_branch(&repo, "disk/api", "main");
    let wt = wt.to_str().unwrap();

    let out = repo.atelier(&[
        "task",
        "build",
        "disk/api",
        "goal=Do it",
        "files=a.rs",
        "done=tests pass",
        "risks=none",
    ]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    let (_, text) = task_file(&out);
    assert!(text.starts_with("# Task: disk/api\n"), "{text}");
    assert!(
        text.contains(&format!("Worktree: {wt}. Branch: disk/api, built on main.")),
        "{text}"
    );
    assert!(text.contains(&format!("Read {wt}/.atelier/rules/WORKER.md first")));
    assert!(text.contains("**Goal.** Do it"));
    assert!(!text.contains("Notes") && !text.contains("{{") && !text.contains("+++"));
    assert!(!text.contains("which may still change"));

    // Optional field, and a stacked branch.
    let wt2 = start_branch(&repo, "disk/ui", "disk/api");
    let out = repo.atelier(&[
        "task",
        "build-hard",
        "disk/ui",
        "goal=g",
        "files=f",
        "done=d",
        "risks=r",
        "notes=n1",
    ]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    let (_, text) = task_file(&out);
    assert!(text.contains("**Notes.** n1\n"));
    assert!(text.contains("built on disk/api, which may still change"));
    assert!(text.contains(wt2.to_str().unwrap()));

    // review: the diff command from the record's base.
    let base = git(&repo.root, &["rev-parse", "main"]);
    let out = repo.atelier(&["task", "review", "disk/api", "intent=i", "risks=r"]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    let (_, text) = task_file(&out);
    assert!(
        text.contains(&format!("`git diff {base}..disk/api`")),
        "{text}"
    );
    assert!(text.contains("Intent: i"));

    // review --fixes
    let out = repo.atelier(&["task", "review", "disk/api", "--fixes", "findings=1. bad"]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    let (_, text) = task_file(&out);
    assert!(text.starts_with("# Review of fixes: disk/api"));
    assert!(text.trim_end().ends_with("1. bad"));

    // Tasks without a branch.
    let out = repo.atelier(&[
        "task",
        "judge",
        "-",
        "question=q",
        "options=o",
        "facts=f",
        "files=x",
    ]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    assert!(task_file(&out).1.starts_with("# Decision needed\n\nq\n"));
    let out = repo.atelier(&["task", "scout", "-", "questions=q", "where=w"]);
    assert!(
        task_file(&out)
            .1
            .starts_with("Read-only lookup. Answer: q\nLook in: w.")
    );
    let out = repo.atelier(&["task", "gui", "-", "app=Notes", "steps=s", "report=r"]);
    assert!(
        task_file(&out)
            .1
            .starts_with("One bounded GUI task in Notes: s")
    );
}

#[test]
fn task_refuses_bad_fields_and_branches() {
    let repo = inited();
    repo.write_agents_file(AGENTS);
    start_branch(&repo, "b1", "main");
    let run = |args: &[&str]| {
        let mut a = vec!["task"];
        a.extend(args);
        let out = repo.atelier(&a);
        (code(&out), stderr(&out))
    };
    let (c, e) = run(&["build", "b1", "goal=g", "files=f"]);
    assert_eq!(c, 2);
    assert!(
        e.contains("missing field(s) for template build: done, risks"),
        "{e}"
    );
    let (c, e) = run(&[
        "build", "b1", "goal=g", "files=f", "done=d", "risks=r", "colour=x",
    ]);
    assert_eq!(c, 2);
    assert!(
        e.contains("unknown field(s) for template build: colour"),
        "{e}"
    );
    let (c, e) = run(&[
        "build", "b1", "goal=g", "files=f", "done=d", "risks=r", "branch=x",
    ]);
    assert_eq!(c, 2);
    assert!(e.contains("unknown field"), "{e}");
    let (c, e) = run(&[
        "build", "nobranch", "goal=g", "files=f", "done=d", "risks=r",
    ]);
    assert_eq!(c, 2);
    assert!(e.contains("start it with atelier start"), "{e}");
    let (c, e) = run(&["build", "-", "goal=g", "files=f", "done=d", "risks=r"]);
    assert_eq!(c, 2);
    assert!(e.contains("needs a branch"), "{e}");
    let (c, e) = run(&["nope", "b1"]);
    assert_eq!(c, 2);
    assert!(e.contains("no role"), "{e}");
    let (c, e) = run(&["build", "b1", "goal", "files=f"]);
    assert_eq!(c, 2, "{e}");
    let (c, e) = run(&["build", "b1", "goal=@/no/such/file"]);
    assert_eq!(c, 2, "{e}");
    assert!(!repo.root.join(".git/atelier/tasks").exists());
}

#[test]
fn task_values_from_files_and_project_overrides() {
    let repo = inited();
    repo.write_agents_file(AGENTS);
    start_branch(&repo, "b1", "main");
    fs::write(repo.root.join("goal.md"), "line one\nline {{two}}\n\n").unwrap();
    let out = repo.atelier(&[
        "task",
        "build",
        "b1",
        "goal=@goal.md",
        "files=f",
        "done=d",
        "risks=r",
    ]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    assert!(
        task_file(&out)
            .1
            .contains("**Goal.** line one\nline {{two}}\n\n**Files.**")
    );

    // A project's template overrides the shipped one; it needs no rules change.
    repo.write(
        ".atelier/tasks/scout.md",
        "+++\nfields = [\"q\"]\noptional = [\"extra\"]\n+++\nMine: {{q}} on {{rules}}{{#extra}} +{{extra}}{{/extra}}\n",
    );
    let out = repo.atelier(&["task", "scout", "-", "q=why"]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    let text = task_file(&out).1;
    assert_eq!(
        text,
        format!("Mine: why on {}/.atelier/rules\n", repo.root.display())
    );
    let out = repo.atelier(&["task", "scout", "-", "q=why", "extra=x"]);
    assert!(task_file(&out).1.contains(" +x"));
    // The old fields are unknown to the override.
    let out = repo.atelier(&["task", "scout", "-", "questions=q", "where=w"]);
    assert_eq!(code(&out), 2);

    // A template using an undeclared name is refused as a broken template.
    repo.write(
        ".atelier/tasks/gui.md",
        "+++\nfields = []\n+++\n{{mystery}}\n",
    );
    let out = repo.atelier(&["task", "gui", "-"]);
    assert_eq!(code(&out), 4, "{}", stderr(&out));
    assert!(stderr(&out).contains("mystery"));
}
