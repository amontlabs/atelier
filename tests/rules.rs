const AGENTS: &str = r#"
[roles.build]
for = "an ordinary item or fix"
start = "delegate_task, target.model = build"
template = "build"
[roles.build-hard]
for = "hard items"
start = "delegate_task, target.model = build-hard"
template = "build"
[roles.review]
for = "reviews"
start = "Agent, model = review"
template = "review"
[roles.judge]
for = "design calls"
start = "Agent, model = judge"
template = "judge"
[roles.scout]
for = "lookups"
start = "Agent, model = scout"
template = "scout"
[roles.gui]
for = "GUI steps"
start = "Agent, model = computer-use"
template = "gui"
"#;

fn inited() -> Repo {
    let repo = Repo::new();
    repo.install_self(VERSION);
    let out = repo.atelier(&["init", "--version", VERSION]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    repo
}

fn read(repo: &Repo, rel: &str) -> String {
    fs::read_to_string(repo.root.join(rel)).unwrap()
}

#[test]
fn init_writes_everything_and_refuses_twice() {
    let repo = inited();
    let toml = read(&repo, ".atelier/atelier.toml");
    assert!(toml.contains(&format!("atelier = \"{VERSION}\"")));
    assert!(toml.contains("integration_branch = \"main\""));
    for f in ["binding.md", "worker.md", "orchestrator.md"] {
        assert_eq!(read(&repo, &format!(".atelier/project/{f}")), "");
    }
    assert!(read(&repo, ".atelier/rules/WORKER.md").starts_with("# Worker rules"));
    assert!(read(&repo, ".atelier/rules/ORCHESTRATOR.md").starts_with("# Orchestrator rules"));
    let agents = read(&repo, "AGENTS.md");
    assert!(agents.starts_with("<!-- atelier:begin (generated by atelier"));
    assert!(agents.contains("## Agent workflow"));
    assert!(agents.ends_with("<!-- atelier:end -->\n"));
    assert_eq!(read(&repo, "CLAUDE.md"), "@AGENTS.md\n");
    let out = repo.atelier(&["init"]);
    assert_eq!(code(&out), 4);
    // The project is current right after init.
    let out = repo.atelier(&["rules"]);
    assert_eq!(code(&out), 0, "{}", stderr(&out));
    assert!(stdout(&out).contains("current"));
}

#[test]
fn init_keeps_existing_agents_and_claude_text() {
    let repo = Repo::new();
    repo.install_self(VERSION);
    repo.write("AGENTS.md", "# Mine\n\ntext");
    repo.write("CLAUDE.md", "notes");
    assert_eq!(code(&repo.atelier(&["init", "--version", VERSION])), 0);
    let agents = read(&repo, "AGENTS.md");
    assert!(agents.starts_with("# Mine\n\ntext\n\n<!-- atelier:begin"));
    assert_eq!(read(&repo, "CLAUDE.md"), "notes\n@AGENTS.md\n");
    // Broken markers: init refuses and leaves no .atelier/.
    let repo = Repo::new();
    repo.install_self(VERSION);
    repo.write("AGENTS.md", "<!-- atelier:begin x -->\n");
    let out = repo.atelier(&["init", "--version", VERSION]);
    assert_eq!(code(&out), 4, "{}", stderr(&out));
    assert!(!repo.root.join(".atelier").exists());
}

#[test]
fn rules_verify_catches_each_kind_of_drift() {
    let repo = inited();
    type Drift = (&'static str, Box<dyn Fn(&Repo)>);
    let drift: Vec<Drift> = vec![
        (
            "one byte in WORKER.md",
            Box::new(|r| {
                r.write(
                    ".atelier/rules/WORKER.md",
                    &(read(r, ".atelier/rules/WORKER.md") + " "),
                )
            }),
        ),
        (
            "missing ORCHESTRATOR.md",
            Box::new(|r| fs::remove_file(r.root.join(".atelier/rules/ORCHESTRATOR.md")).unwrap()),
        ),
        (
            "extra file",
            Box::new(|r| r.write(".atelier/rules/EXTRA.md", "x")),
        ),
        (
            "block edited",
            Box::new(|r| {
                r.write(
                    "AGENTS.md",
                    &read(r, "AGENTS.md").replace("No CI waits", "CI waits"),
                )
            }),
        ),
        (
            "end marker missing",
            Box::new(|r| {
                r.write(
                    "AGENTS.md",
                    &read(r, "AGENTS.md").replace("<!-- atelier:end -->\n", ""),
                )
            }),
        ),
        (
            "markers doubled",
            Box::new(|r| {
                let a = read(r, "AGENTS.md");
                r.write("AGENTS.md", &format!("{a}{a}"));
            }),
        ),
        (
            "import line gone",
            Box::new(|r| r.write("CLAUDE.md", "nothing\n")),
        ),
        (
            "project text changed",
            Box::new(|r| r.write(".atelier/project/worker.md", "## Mine\n- rule\n")),
        ),
    ];
    for (what, f) in drift {
        f(&repo);
        let out = repo.atelier(&["agents"]);
        assert_eq!(code(&out), 4, "{what}: {}", stderr(&out));
        assert!(
            stderr(&out).contains("rules are stale: run atelier rules"),
            "{what}"
        );
        // status reports it instead of stopping.
        assert!(
            stdout(&repo.atelier(&["status"])).contains("FAILED rules"),
            "{what}"
        );
        let mut out = repo.atelier(&["rules"]);
        if what.contains("marker") || what.contains("doubled") {
            // Broken markers are never guessed at: rules refuses until they are fixed by hand.
            assert_eq!(code(&out), 4, "{what}");
            repo.write("AGENTS.md", "");
            out = repo.atelier(&["rules"]);
        }
        assert_eq!(code(&out), 0, "{what}: {}", stderr(&out));
        repo.write_agents_file(AGENTS);
        assert_eq!(code(&repo.atelier(&["agents"])), 0, "{what} after rules");
    }
    // Project text reaches the generated files.
    repo.write(".atelier/project/worker.md", "## Mine\n- rule\n");
    repo.write(".atelier/project/binding.md", "Never touch prod.\n");
    assert_eq!(code(&repo.atelier(&["rules"])), 0);
    assert!(read(&repo, ".atelier/rules/WORKER.md").ends_with("\n## Mine\n- rule\n"));
    let a = read(&repo, "AGENTS.md");
    assert!(
        a.ends_with("Never touch prod.\n<!-- atelier:end -->\n"),
        "{a}"
    );
}

#[test]
fn optional_sections_follow_the_settings() {
    let repo = inited();
    let worker = read(&repo, ".atelier/rules/WORKER.md");
    assert!(!worker.contains("Another platform"));
    assert!(!worker.contains("cargo"));
    assert!(!read(&repo, ".atelier/rules/ORCHESTRATOR.md").contains("on every platform"));

    let mut toml = read(&repo, ".atelier/atelier.toml");
    toml.push_str("[platforms.linux-x86_64]\nrun = [\"true\"]\n");
    repo.write(".atelier/atelier.toml", &toml);
    assert_eq!(code(&repo.atelier(&["rules"])), 0);
    assert!(read(&repo, ".atelier/rules/WORKER.md").contains("- Another platform:"));
    assert!(read(&repo, ".atelier/rules/ORCHESTRATOR.md").contains("on every platform"));

    let mut toml = read(&repo, ".atelier/atelier.toml");
    toml.push_str("\n[rust]\nnextest = \"0.9.151\"\n");
    repo.write(".atelier/atelier.toml", &toml);
    assert_eq!(code(&repo.atelier(&["rules"])), 0);
    assert!(read(&repo, ".atelier/rules/WORKER.md").contains("Use plain `cargo`"));
}

