#[test]
fn import_into_refuses_names_that_damage_other_files() {
    let repo = inited();
    let base = read(&repo, ".atelier/atelier.toml");
    for name in [
        "AGENTS.md",
        ".git",
        ".GIT",
        "../x.md",
        "/etc/x.md",
        "docs/x.md",
        "..",
        ".git/info",
    ] {
        repo.write(
            ".atelier/atelier.toml",
            &format!("{base}\n[rules]\nimport_into = [{name:?}]\n"),
        );
        let out = repo.atelier(&["rules"]);
        assert_eq!(code(&out), 4, "{name}: {}", stderr(&out));
        assert!(stderr(&out).contains("rules.import_into"), "{name}");
    }
    // A name that is the same file as AGENTS.md on this volume: a case alias where the volume
    // ignores case, or a hard link anywhere.
    std::fs::hard_link(repo.root.join("AGENTS.md"), repo.root.join("OTHER.md")).unwrap();
    repo.write(
        ".atelier/atelier.toml",
        &format!("{base}\n[rules]\nimport_into = [\"OTHER.md\"]\n"),
    );
    let out = repo.atelier(&["rules"]);
    assert_eq!(code(&out), 4, "{}", stderr(&out));
    assert!(stderr(&out).contains("same file"), "{}", stderr(&out));
    fs::remove_file(repo.root.join("OTHER.md")).unwrap();
    let insensitive = repo.root.join(".GIT").exists();
    repo.write(
        ".atelier/atelier.toml",
        &format!("{base}\n[rules]\nimport_into = [\"agents.md\"]\n"),
    );
    let out = repo.atelier(&["rules"]);
    if insensitive {
        assert_eq!(code(&out), 4, "{}", stderr(&out));
        assert!(stderr(&out).contains("rules.import_into"));
    } else {
        // A different file here: it gets the import line.
        assert_eq!(code(&out), 0, "{}", stderr(&out));
        assert_eq!(read(&repo, "agents.md"), "@AGENTS.md\n");
    }
}

