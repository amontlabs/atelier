/// Runs `f` with a folder that cannot be written to, unless this process ignores permissions.
fn with_locked_dir(repo: &Repo, f: impl FnOnce()) {
    use std::os::unix::fs::PermissionsExt;
    let dir = repo.root.join("locked");
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("claude.md"), "notes\n").unwrap();
    fs::set_permissions(&dir, fs::Permissions::from_mode(0o555)).unwrap();
    let writable = fs::write(dir.join("probe"), "x").is_ok();
    if !writable {
        f();
    }
    fs::set_permissions(&dir, fs::Permissions::from_mode(0o755)).unwrap();
}

#[test]
fn a_failed_init_restores_agents_and_claude_md() {
    // AGENTS.md existed: its text comes back.
    let repo = Repo::new();
    repo.write("AGENTS.md", "# Mine\n");
    with_locked_dir(&repo, || {
        std::os::unix::fs::symlink("locked/claude.md", repo.root.join("CLAUDE.md")).unwrap();
        let out = init_with(&repo);
        assert_ne!(code(&out), 0);
        assert_eq!(read(&repo, "AGENTS.md"), "# Mine\n");
        assert_eq!(read(&repo, "locked/claude.md"), "notes\n");
        assert!(is_link(&repo, "CLAUDE.md"));
        assert!(!repo.root.join(".atelier").exists());
    });
    // init created AGENTS.md: it is removed again.
    let repo = Repo::new();
    with_locked_dir(&repo, || {
        std::os::unix::fs::symlink("locked/claude.md", repo.root.join("CLAUDE.md")).unwrap();
        assert_ne!(code(&init_with(&repo)), 0);
        assert!(!repo.root.join("AGENTS.md").exists());
        assert_eq!(read(&repo, "locked/claude.md"), "notes\n");
        assert!(!repo.root.join(".atelier").exists());
    });
}

